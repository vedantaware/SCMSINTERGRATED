
create table if not exists public.users (
 id bigint generated by default as identity primary key,
 name text not null,
 email text unique not null,
 password text not null,
 role text not null,
 portfolio text default '',
 phone text default '',
 class_name text default '',
 branch text default '',
 is_active boolean default true,
 created_at timestamptz default now()
);

create table if not exists public.teams (
 id bigint generated by default as identity primary key,
 slug text unique not null,
 name text not null,
 lead_user_id bigint references public.users(id),
 faculty_coordinator_id bigint references public.users(id),
 description text default '',
 source_page integer,
 source_note text default '',
 created_at timestamptz default now()
);

create table if not exists public.team_budgets (
 id bigint generated by default as identity primary key,
 team_id bigint not null unique references public.teams(id) on delete cascade,
 fiscal_year text default '2026-27',
 allocated_amount numeric default 0,
 notes text default '',
 updated_by bigint references public.users(id),
 updated_at timestamptz default now()
);

create table if not exists public.budget_transactions (
 id bigint generated by default as identity primary key,
 team_id bigint not null references public.teams(id) on delete cascade,
 title text not null,
 amount numeric not null,
 transaction_type text default 'Expense',
 status text default 'Approved',
 reference text default '',
 created_by bigint references public.users(id),
 created_at timestamptz default now()
);

create table if not exists public.team_members (
 id bigint generated by default as identity primary key,
 team_id bigint not null references public.teams(id) on delete cascade,
 user_id bigint not null references public.users(id) on delete cascade,
 position text default 'Committee Member',
 is_lead boolean default false,
 joined_at timestamptz default now(),
 unique(team_id,user_id)
);

