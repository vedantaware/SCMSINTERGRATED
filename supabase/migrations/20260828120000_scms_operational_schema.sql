alter table public.tasks add column if not exists assigned_by bigint;
alter table public.tasks add column if not exists team_id bigint;
alter table public.tasks add column if not exists due_date text default '';
alter table public.tasks add column if not exists due_time text default '';
alter table public.tasks add column if not exists updated_at timestamptz default now();
alter table public.tasks add column if not exists comments text default '';

create table if not exists public.events (
 id bigint generated by default as identity primary key,
 title text not null,
 date text not null,
 start_time text default '',
 end_time text default '',
 location text default '',
 event_type text default 'General',
 priority text default 'Normal',
 description text default '',
 organizer text default '',
 capacity integer default 0,
 team_id bigint references public.teams(id),
 status text default 'Proposed',
 budget_allocated numeric default 0,
 created_by bigint references public.users(id),
 created_at timestamptz default now()
);

create table if not exists public.meetings (
 id bigint generated by default as identity primary key,
 title text not null,
 date text not null,
 time text default '',
 location text default '',
 meeting_type text default 'Regular',
 agenda text default '',
 minutes text default '',
 action_items text default '',
 team_id bigint references public.teams(id),
 created_by bigint references public.users(id),
 status text default 'Scheduled',
 completed_at timestamptz,
 created_at timestamptz default now()
);

alter table public.meetings add column if not exists status text default 'Scheduled';
alter table public.meetings add column if not exists completed_at timestamptz;

create table if not exists public.finances (
 id bigint generated by default as identity primary key,
 title text not null,
 amount numeric not null,
 type text default 'Operations',
 priority text default 'Normal',
 status text default 'Pending',
 requested_by bigint references public.users(id),
 approved_by bigint references public.users(id),
 team_id bigint references public.teams(id),
 vendor text default '',
 justification text default '',
 receipt_url text default '',
 created_at timestamptz default now(),
 updated_at timestamptz default now()
);

create table if not exists public.grievances (
 id bigint generated by default as identity primary key,
 subject text not null,
 description text not null,
 category text default 'General',
 department text default '',
 contact_preference text default 'Portal notification',
 is_anonymous boolean default false,
 follow_up_allowed boolean default true,
 priority text default 'Normal',
 status text default 'Open',
 created_by bigint references public.users(id),
 assigned_to bigint references public.users(id),
 resolution_notes text default '',
 created_at timestamptz default now(),
 updated_at timestamptz default now()
);

create table if not exists public.announcements (
 id bigint generated by default as identity primary key,
 title text not null,
 content text not null,
 audience text default 'Council',
 team_id bigint references public.teams(id),
 created_by bigint references public.users(id),
 created_at timestamptz default now()
);

create table if not exists public.goals (
 id bigint generated by default as identity primary key,
 team_id bigint not null references public.teams(id),
 title text not null,
 description text default '',
 owner_id bigint references public.users(id),
 target_date text default '',
 status text default 'Planned',
 progress integer default 0,
 created_by bigint references public.users(id),
 created_at timestamptz default now(),
 updated_at timestamptz default now()
);

create table if not exists public.documents (
 id bigint generated by default as identity primary key,
 team_id bigint references public.teams(id),
 title text not null,
 description text default '',
 file_url text not null,
 document_type text default 'Reference',
 created_by bigint references public.users(id),
 created_at timestamptz default now()
);

create table if not exists public.approvals (
 id bigint generated by default as identity primary key,
 team_id bigint references public.teams(id),
 title text not null,
 description text default '',
 approval_type text default 'General',
 requested_by bigint references public.users(id),
 reviewed_by bigint references public.users(id),
 status text default 'Pending',
 review_notes text default '',
 created_at timestamptz default now(),
 updated_at timestamptz default now()
);

create table if not exists public.notifications (
 id bigint generated by default as identity primary key,
 user_id bigint not null references public.users(id) on delete cascade,
 title text not null,
 message text not null,
 kind text default 'info',
 is_read boolean default false,
 created_at timestamptz default now()
);

create table if not exists public.audit_logs (
 id bigint generated by default as identity primary key,
 actor_id bigint references public.users(id),
 action text not null,
 entity_type text not null,
 entity_id bigint,
 details text default '',
 created_at timestamptz default now()
);

create table if not exists public.council_meta (
 key text primary key,
 value text
);

